"""Replay the shared EventManager test vectors (tests/vectors/event_manager_*.json) on the Python manager.

The C port in engine/src/core/event_manager.c replays the same files in `make test-core`. The files
are generated by tests/vectors/generate_event_manager_vectors.py from this very manager, so a failure
here means the specification changed without regenerating the vectors.
"""

import json
from datetime import datetime, timedelta
from pathlib import Path

import pytest

from src.events import PersonDetectedEventManager

VECTOR_DIR = Path(__file__).resolve().parent / "vectors"
VECTOR_FILES = sorted(VECTOR_DIR.glob("event_manager_*.json"))
EPOCH = datetime(1970, 1, 1)


def clock(now_ns: int) -> datetime:
    return EPOCH + timedelta(microseconds=now_ns // 1000)


def test_vectors_exist():
    assert VECTOR_FILES, f"no event_manager_*.json in {VECTOR_DIR}"


@pytest.mark.parametrize("path", VECTOR_FILES, ids=lambda p: p.stem)
def test_vector(path):
    vector = json.loads(path.read_text(encoding="utf-8"))
    manager = PersonDetectedEventManager(absence_timeout=vector["absence_timeout_s"])

    for index, step in enumerate(vector["steps"]):
        assert step["now_ns"] % 1000 == 0, f"step {index}: now_ns must be a multiple of 1000"
        now = clock(step["now_ns"])

        events = manager.process([(d["track_id"], d["conf"]) for d in step["detections"]], now=now)

        assert [(e.track_id, e.confidence) for e in events] == [
            (e["track_id"], e["confidence"]) for e in step["expected_events"]
        ], f"step {index}: events"
        assert all(e.event_type == "PERSON_DETECTED" and e.timestamp == now for e in events), f"step {index}"
        assert len(manager._tracks) == step["tracks_after"], f"step {index}: tracks_after"
